/**
 * The shim generator (INJ-01): what a Hybrid build adds to the user's
 * unchanged sketch so virtual parts can answer it.
 *
 * Mechanism, as proved in the Sprint 2 spike (docs/phase-two/sprint-2-spike-results.md):
 * a header forced into every C++ compile with `-include`. It renames the
 * sketch's `Serial` and the pin-reading functions to the Kiungo runtime's,
 * while the core's own files are left alone because only the sketch and
 * libraries see the KiungoHybrid include path. LTO stays on; `--wrap` is
 * not used, because LTO silently drops it on the Arduino toolchain.
 *
 * Sensors with their own libraries (NewPing today; DHT at launch) are
 * swapped at the library level with an adapter of the same name.
 */

import { MAX_SENSORS } from "./protocol";

/** A part whose readings the PC will push. `pins` are the Arduino pin numbers the sketch reads it on. */
export interface VirtualSensor {
  /** 0 to MAX_SENSORS-1; the id in SET frames. */
  id: number;
  /** The Kiungo part id (e.g. "hc-sr04", "ldr", "button"). */
  part: string;
  /** Which adapter library stands in for the real one, if the part needs one. */
  adapter?: "NewPing";
  /** Pins the sketch reads this sensor on: the trigger pin for an HC-SR04, the data pin for a button. */
  pins: number[];
}

export interface HybridPlan {
  board: "arduino:avr:uno" | "arduino:avr:nano";
  sensors: VirtualSensor[];
}

export interface ShimOutput {
  /** The forced-include header, to write as kiungo_shim.h in the build folder. */
  header: string;
  /** Extra C++ compiler flags: the forced include. */
  cppFlags: string[];
  /** Adapter libraries to add with `--library`, by name under resources/hybrid/adapters. */
  adapters: string[];
  /** The pin table, for tests and the UI: pin -> sensor id, 0xFF when real. */
  pinTable: number[];
}

const PIN_COUNT = 20; // Uno and Nano: D0-D13, A0-A5 (14-19)

export function pinTable(plan: HybridPlan): number[] {
  const table = new Array<number>(PIN_COUNT).fill(0xff);
  const seen = new Set<number>();
  for (const sensor of plan.sensors) {
    if (!Number.isInteger(sensor.id) || sensor.id < 0 || sensor.id >= MAX_SENSORS) throw new Error(`Sensor id ${sensor.id} is out of range (0 to ${MAX_SENSORS - 1}).`);
    if (seen.has(sensor.id)) throw new Error(`Sensor id ${sensor.id} is used twice.`);
    seen.add(sensor.id);
    for (const pin of sensor.pins) {
      if (!Number.isInteger(pin) || pin < 0 || pin >= PIN_COUNT) throw new Error(`Pin ${pin} doesn't exist on this board.`);
      if (table[pin] !== 0xff) throw new Error(`Pin ${pin} is read by two virtual sensors.`);
      table[pin] = sensor.id;
    }
  }
  return table;
}

export function generateShim(plan: HybridPlan, shimHeaderPath = "kiungo_shim.h"): ShimOutput {
  const table = pinTable(plan);
  const adapters = [...new Set(plan.sensors.map((s) => s.adapter).filter((a): a is "NewPing" => Boolean(a)))];
  const comment = plan.sensors.length
    ? plan.sensors.map((s) => `//   sensor ${s.id}: ${s.part} on pin${s.pins.length === 1 ? "" : "s"} ${s.pins.join(", ")}${s.adapter ? ` (adapter: ${s.adapter})` : ""}`).join("\n")
    : "//   no virtual sensors: only Serial is redirected";
  const header = `// Generated by Kiungo for a Hybrid build. Do not edit; it is rewritten on every build.
// Forced into every C++ compile with -include. The core's own files are not
// affected: they don't have the KiungoHybrid include path, so the marker is absent.
//
// Virtual parts in this build:
${comment}
#pragma once
#if __has_include(<kiungo_hybrid_marker.h>)
#include <Arduino.h>
#define KIUNGO_PIN_TABLE {${table.map((v) => "0x" + v.toString(16).padStart(2, "0")).join(", ")}}
#include <kiungo_hybrid.h>
#define Serial kiungoSerial
#define serialEvent kiungo_user_serialEvent
#define digitalRead kiungo_digitalRead
#define analogRead kiungo_analogRead
#define pulseIn kiungo_pulseIn
#define pulseInLong kiungo_pulseInLong
#endif
`;
  return { header, cppFlags: ["-include", shimHeaderPath], adapters, pinTable: table };
}

/** The plan for the Sprint 2 hardware check: one virtual HC-SR04 on D9 (trigger) and D10 (echo). */
export const SPRINT_2_PLAN: HybridPlan = {
  board: "arduino:avr:uno",
  sensors: [{ id: 0, part: "hc-sr04", adapter: "NewPing", pins: [9, 10] }],
};
